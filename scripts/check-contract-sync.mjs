#!/usr/bin/env node
// Progress contract sync check (plan B4). The farmer tracker reads its whole vocabulary (stages,
// statuses, explanation keys, actions, satellite statuses and reason codes) from a COPY of the
// backend's machine-readable contract. This script fails when the copy and the backend file differ,
// so a backend change to the contract cannot ship without the frontend copy, its translations and
// its tests being updated in the same change.
//
//   node scripts/check-contract-sync.mjs          (npm run contract:check)
//
// The backend checkout is looked up at $VIVASAYI_BACKEND_DIR, else ../VivasayiAI next to this repo.
// Exit codes: 0 in sync, 1 out of sync, 2 a file is missing (the check could not run).
//
// The example fixture (the backend builder's own output, used by the CT tests) is compared too: it
// is generated by the backend from the same builder, so a stale copy means stale parser tests.

import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const backendRoot = resolve(process.env.VIVASAYI_BACKEND_DIR || resolve(frontendRoot, '..', 'VivasayiAI'));

const PAIRS = [
  {
    label: 'progress contract',
    frontend: 'src/contracts/progress-contract-v1.json',
    backend: 'docs/architecture/progress-contract-v1.json',
  },
  {
    label: 'progress example fixture',
    frontend: 'src/test/fixtures/progress-v1.example.json',
    backend: 'docs/architecture/progress-v1.example.json',
  },
];

const sha256 = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');

let missing = false;
let mismatched = false;

for (const pair of PAIRS) {
  const frontendPath = resolve(frontendRoot, pair.frontend);
  const backendPath = resolve(backendRoot, pair.backend);
  if (!existsSync(frontendPath) || !existsSync(backendPath)) {
    missing = true;
    console.error(
      `MISSING  ${pair.label}: ${existsSync(frontendPath) ? '' : `${frontendPath} `}${existsSync(backendPath) ? '' : backendPath}`.trim()
    );
    continue;
  }
  const frontendHash = sha256(frontendPath);
  const backendHash = sha256(backendPath);
  if (frontendHash === backendHash) {
    console.log(`OK       ${pair.label}  sha256 ${frontendHash}`);
  } else {
    mismatched = true;
    console.error(`MISMATCH ${pair.label}`);
    console.error(`         frontend ${frontendHash}  ${pair.frontend}`);
    console.error(`         backend  ${backendHash}  ${backendPath}`);
  }
}

if (mismatched) {
  console.error(
    '\nThe frontend copy is out of date. Copy the backend file(s) over the frontend copy, then add or update the\n' +
      'en/ta strings the I18N-P tests ask for (src/contracts/progressContract.test.ts) and re-run the tests.'
  );
  process.exit(1);
}
if (missing) {
  console.error('\nSet VIVASAYI_BACKEND_DIR to the backend checkout if it is not at ../VivasayiAI.');
  process.exit(2);
}
console.log(`Progress contract in sync with ${backendRoot}`);
